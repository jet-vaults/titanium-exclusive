export function familyKey(product) {
  const n = product.name.toLowerCase();
  const cat = product.categories[0] ? product.categories[0].slug : '';
  if (product.family === 'set') return 'set';
  if (product.family === 'lid') return 'lid';
  if (product.family === 'steamer-insert') return 'steamer';
  if (product.family !== 'cookware') return 'other';
  if (/frying|crepe|crêpe/.test(n) || cat === 'titanium-frying-pans') return 'frying';
  if (cat === 'titanium-sauce-pans') return 'sauce';
  if (cat === 'titanium-casserole-pans' || /casserole/.test(n)) return 'casserole';
  if (cat === 'titanium-roasting-pots') return 'roasting';
  if (cat === 'titanium-soup-pots' || cat === 'steamers') return 'soup';
  if (cat === 'titanium-large-roasting-pans') return 'roaster';
  return 'specialty';
}
